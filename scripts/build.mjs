/**
 * Bundle the standalone preview into one self-contained iframe document.
 *
 * The plugin deliberately serves a single HTML file: the host injects an
 * iframe, and the iframe owns its CSS/JS. That keeps the splash from leaking
 * styles into the DSH app and makes the same artifact usable from a file://
 * preview.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const read = (name) => fs.readFileSync(path.join(ROOT, name), 'utf8')
const write = (name, text) => {
  const file = path.join(ROOT, name)
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, text, 'utf8')
  return { file, bytes: Buffer.byteLength(text) }
}

const escapeScript = (js) => js.replace(/<\/script/gi, '<\\/script')
const escapeStyle = (css) => css.replace(/<\/style/gi, '<\\/style')

let html = read('index.html')
const css = read('boot.css')
const whale = read('whale-path.js')
const boot = read('boot.js')

html = html.replace(
  '<link rel="stylesheet" href="boot.css">',
  '<style>\n' + escapeStyle(css) + '\n</style>'
)
html = html.replace(
  '<script src="whale-path.js"></script>',
  '<script>\n' + escapeScript(whale) + '\n</script>'
)
html = html.replace(
  '<script src="boot.js"></script>',
  '<script>\n' + escapeScript(boot) + '\n</script>'
)

if (/(?:src|href)="(?:boot\.css|boot\.js|whale-path\.js)"/.test(html)) {
  throw new Error('build: an external local asset reference survived inlining')
}
if (!html.includes('dsh-cinematic:ready') || !html.includes('is-embed')) {
  throw new Error('build: embed hooks are missing from boot.js')
}

const banner = '<!-- generated by scripts/build.mjs; edit index.html / boot.css / boot.js instead -->\n'
html = html.replace('<!doctype html>', '<!doctype html>\n' + banner)

const out = write('lib/boot.html', html)
console.log(`built ${path.relative(ROOT, out.file)} (${(out.bytes / 1024).toFixed(1)} KiB)`)
